#!/usr/bin/env python3
"""Generate sw/test_muldiv.S: every M-extension operation on every pair of interesting operand values.

usage: gen_muldiv_test.py            writes sw/test_muldiv.S
       gen_muldiv_test.py <code>     explains an exit code of the generated program

The expected values come from the reference model below (Python integers, written from the RISC-V spec),
which has nothing in common with the RTL or with the C++ model of the unit test.
"""
import sys

M32 = 0xFFFFFFFF
VALUES = [0, 1, 2, 3, 7, 0xFFFFFFFF, 0xFFFFFFFE, 0x80000000, 0x80000001, 0x7FFFFFFF,
          0x7FFFFFFE, 0x00010000, 0x0000FFFF, 0xFFFF0000, 12345, 0xDEADBEEF]
OPS = ["mul", "mulh", "mulhsu", "mulhu", "div", "divu", "rem", "remu"]


def signed(x):
    return x - (1 << 32) if x >> 31 else x


def ref(op, a, b):
    sa, sb = signed(a), signed(b)
    if op == 0: return (a * b) & M32
    if op == 1: return ((sa * sb) >> 32) & M32          # >> on a negative Python int is arithmetic
    if op == 2: return ((sa * b) >> 32) & M32
    if op == 3: return ((a * b) >> 32) & M32
    if op == 4:                                          # div: toward zero; /0 gives all ones; overflow gives INT_MIN
        if b == 0: return M32
        if sa == -(1 << 31) and sb == -1: return a
        q = abs(sa) // abs(sb)
        return (-q if (sa < 0) != (sb < 0) else q) & M32
    if op == 5: return M32 if b == 0 else a // b
    if op == 6:                                          # rem: sign of the dividend; %0 gives the dividend
        if b == 0: return a
        if sa == -(1 << 31) and sb == -1: return 0
        r = abs(sa) % abs(sb)
        return (-r if sa < 0 else r) & M32
    return a if b == 0 else a % b


def explain(code):
    entry, op = divmod(code - 1, 8)
    a, b = VALUES[entry // len(VALUES)], VALUES[entry % len(VALUES)]
    print(f"exit code {code}: {OPS[op]}, a=0x{a:08x} b=0x{b:08x}, expected 0x{ref(op, a, b):08x}")


def main():
    if len(sys.argv) == 2:
        explain(int(sys.argv[1]))
        return
    out = ["# Generated by scripts/gen_muldiv_test.py: every M operation on every pair of interesting values.",
           "# Exit code: 0 = all good, otherwise 8*entry + operation index (1..8): scripts/gen_muldiv_test.py <code> explains it.",
           "    .globl _start",
           "_start:",
           "    la   s0, table             # current entry: a, b, then the expected results of the 8 operations",
           "    la   s1, table_end",
           "    li   s2, 0                 # entry number",
           "loop:",
           "    lw   a0, 0(s0)",
           "    lw   a1, 4(s0)"]
    for i, name in enumerate(OPS):
        out += [f"    {name:6s} a2, a0, a1",
                f"    lw   a3, {8 + 4 * i}(s0)",
                f"    beq  a2, a3, ok{i}",
                "    slli t0, s2, 3",
                f"    addi t0, t0, {i + 1}",
                "    j    fail",
                f"ok{i}:"]
    out += ["    addi s0, s0, 40",
            "    addi s2, s2, 1",
            "    bne  s0, s1, loop",
            "    lui  t6, 0x20000           # success: exit code 0",
            "    sw   x0, 0(t6)",
            "fail:",
            "    lui  t6, 0x20000",
            "    sw   t0, 0(t6)",
            "",
            "    .data",
            "    .balign 4",
            "table:"]
    for a in VALUES:
        for b in VALUES:
            words = [a, b] + [ref(op, a, b) for op in range(8)]
            out.append("    .word " + ", ".join(f"0x{w:08x}" for w in words))
    out += ["table_end:", ""]
    with open("sw/test_muldiv.S", "w") as f:
        f.write("\n".join(out))
    print(f"wrote sw/test_muldiv.S: {len(VALUES) ** 2} entries x 8 operations = {len(VALUES) ** 2 * 8} checks")


main()
